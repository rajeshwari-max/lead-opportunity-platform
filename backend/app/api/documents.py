"""Signed opportunity-document links with an official-file-first policy."""
from __future__ import annotations

from fastapi import APIRouter, Depends, HTTPException, Query
from fastapi.responses import Response
from sqlalchemy.orm import Session

from app.database.db import get_db
from app.database.models import Opportunity
from app.services.opportunity_pdf import brief_signature_ok

router = APIRouter(tags=["documents"])


@router.get("/brief/{opportunity_id}.pdf")
def opportunity_brief_pdf(opportunity_id: int, sig: str = Query(""),
                          db: Session = Depends(get_db)) -> Response:
    if not brief_signature_ok(opportunity_id, sig):
        raise HTTPException(404, "Not found")
    opportunity = db.get(Opportunity, opportunity_id)
    if opportunity is None:
        raise HTTPException(404, "Not found")
    if opportunity.pdf_status == "found" and opportunity.pdf_url:
        # The source has its own PDF now; send people there.
        from fastapi.responses import RedirectResponse
        return RedirectResponse(opportunity.pdf_url, status_code=302)

    # Not every source publishes a downloadable ToR, and membership sources
    # may expose only the description in their signed-in interface. Give the
    # reader a clearly labelled platform brief rather than a broken/unavailable
    # link. This is never presented as an official source document.
    from io import BytesIO
    from xml.sax.saxutils import escape

    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

    output = BytesIO()
    doc = SimpleDocTemplate(
        output, pagesize=A4, rightMargin=18 * mm, leftMargin=18 * mm,
        topMargin=16 * mm, bottomMargin=16 * mm,
        title=f"Opportunity brief - {opportunity.title}",
    )
    styles = getSampleStyleSheet()
    story = [
        Paragraph("Platform-generated opportunity brief", styles["Heading3"]),
        Paragraph(escape(opportunity.title or "Opportunity"), styles["Title"]),
        Spacer(1, 5 * mm),
    ]
    facts = (
        ("Source", opportunity.source_website),
        ("Organisation", opportunity.organization),
        ("Location", opportunity.location or opportunity.country),
        ("Deadline", opportunity.deadline.isoformat() if opportunity.deadline else "Not listed"),
        ("Amount", opportunity.funding_amount),
        ("Category", getattr(opportunity.category, "value", opportunity.category)),
    )
    for label, value in facts:
        if value:
            story.append(Paragraph(f"<b>{escape(str(label))}:</b> {escape(str(value))}",
                                   styles["BodyText"]))
    story.extend([Spacer(1, 5 * mm), Paragraph("Summary", styles["Heading2"]),
                  Paragraph(escape(opportunity.summary or
                                   "No summary was provided by the source."),
                            styles["BodyText"])])
    if opportunity.eligibility:
        story.extend([Spacer(1, 3 * mm), Paragraph("Eligibility", styles["Heading2"]),
                      Paragraph(escape(opportunity.eligibility), styles["BodyText"])])
    if opportunity.opportunity_url:
        safe_url = escape(opportunity.opportunity_url, {'"': '&quot;'})
        story.extend([Spacer(1, 5 * mm),
                      Paragraph(f'<a href="{safe_url}">Open the original source page</a>',
                                styles["BodyText"])])
    story.extend([Spacer(1, 6 * mm), Paragraph(
        "This PDF was generated by the Lead Scanning Platform from scraped source data. "
        "It is not an official Terms of Reference or source-issued document.",
        styles["Italic"],
    )])
    doc.build(story)
    filename = f"opportunity-{opportunity.id}-brief.pdf"
    return Response(
        output.getvalue(), media_type="application/pdf",
        headers={"Content-Disposition": f'inline; filename="{filename}"'},
    )
